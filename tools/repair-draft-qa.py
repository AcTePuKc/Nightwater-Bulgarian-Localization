def main() -> int:
    path = Path("working/Game.bg.draft.json")
    rows = json.loads(path.read_text(encoding="utf-8"))
    found = set()
    for row in rows:
        if row["key"] in REPAIRS:
            row["target"] = REPAIRS[row["key"]]
            found.add(row["key"])
    missing = set(REPAIRS) - found
    if missing:
        raise SystemExit(f"Repair keys not found: {sorted(missing)}")
    path.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Applied {len(found)} QA repairs to {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
